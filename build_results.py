#!/usr/bin/env python3
"""Generate manuscript numbers from results.json; no hand-transcribed outputs."""
from pathlib import Path
import json
import numpy as np
p=Path(__file__).resolve().parent
r=json.loads((p/'results.json').read_text())
a=r['mixed_term']['recovery']['0.6'];n=r['mixed_term']['recovery']['0.0']
d=r['delayed_dictionary'];s=r['source_mixing'];m={v['condition']:v for v in s['summary']}
vals={'LagP':str(d['selected_lags'][0]*5),'LagC':str(d['selected_lags'][1]*5),
      'ChiMean':f"{a['mean_chi']:.3f}",'ChiSD':f"{a['sd_chi']:.3f}",
      'ChiCoverage':f"{100*a['coverage95']:.1f}\\%",'NullMean':f"{n['mean_chi']:.4f}",
      'FalseConst':str(s['false_gate_wins_constant']),'FalseFourier':str(s['false_gate_wins_fourier'])}
for macro,k in [('DelayAdd','additive'),('DelayInstant','instantaneous'),('DelayFull','delayed'),('DelayQuad','quadratic')]:
    vals[macro]=f"{d['test_mse'][k]:.5f}"
for macro,k in [('MixedAdd','additive_mse'),('MixedFull','mixed_mse'),('MixedQuad','quadratic_mse')]:
    vals[macro]=f"{np.mean(a[k]):.5f}"
for macro,cond,k in [('CleanRMSE','clean10','phase_rmse'),('CleanKappa','clean10','mean_kappa'),('MixedRMSE','mix+drive','phase_rmse'),('MixedKappa','mix+drive','mean_kappa')]:
    vals[macro]=f"{m[cond][k]:.3f}"
for macro,v in zip(['AltGate','AltConst','AltFourier'],s['alternative_generator_mse']):vals[macro]=f'{v:.4f}'
(p/'results_macros.tex').write_text('% Automatically generated by build_results.py\n'+''.join('\\newcommand{\\'+k+'}{'+v+'}\n' for k,v in vals.items()))
print('Generated results_macros.tex from verified JSON.')
